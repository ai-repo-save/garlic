def uleb128(value):
    result = bytearray()
    while value >= 128:
        result.append((value & 127) | 128)
        value >>= 7
    result.append(value)
    return result


def dex_fixture():
    """Minimal DEX035: one class, one static void method, standard map/checksums."""
    strings = ["LDecode;", "Ljava/lang/Object;", "V", "[I", "decode"]
    string_ids_off = 112
    type_ids_off = string_ids_off + 4 * len(strings)
    proto_ids_off = type_ids_off + 4 * 4
    method_ids_off = proto_ids_off + 12
    class_defs_off = method_ids_off + 8
    data_off = class_defs_off + 32
    data = bytearray(data_off)
    string_offsets = []
    for text in strings:
        string_offsets.append(len(data))
        data.extend(uleb128(len(text)) + text.encode() + b"\0")
    while len(data) % 4:
        data.append(0)
    code_off = len(data)
    data.extend(struct.pack("<HHHHII", 65535, 0, 0, 0, 0, len(CODE_UNITS)))
    data.extend(struct.pack(f"<{len(CODE_UNITS)}H", *CODE_UNITS))
    class_data_off = len(data)
    # No fields, one direct method, no virtual methods; method_idx=0, public static.
    data.extend(b"\0\0\1\0\0\x09" + uleb128(code_off))
    while len(data) % 4:
        data.append(0)
    map_off = len(data)
    entries = [
        (0x0000, 1, 0),
        (0x0001, len(strings), string_ids_off),
        (0x0002, 4, type_ids_off),
        (0x0003, 1, proto_ids_off),
        (0x0005, 1, method_ids_off),
        (0x0006, 1, class_defs_off),
        (0x2002, len(strings), string_offsets[0]),
        (0x2001, 1, code_off),
        (0x2000, 1, class_data_off),
        (0x1000, 1, map_off),
    ]
    data.extend(struct.pack("<I", len(entries)))
    for kind, size, offset in entries:
        data.extend(struct.pack("<HHII", kind, 0, size, offset))
    data[:8] = b"dex\n035\0"
    struct.pack_into(
        "<20I",
        data,
        32,
        len(data),
        112,
        0x12345678,
        0,
        0,
        map_off,
        len(strings),
        string_ids_off,
        4,
        type_ids_off,
        1,
        proto_ids_off,
        0,
        0,
        1,
        method_ids_off,
        1,
        class_defs_off,
        len(data) - data_off,
        data_off,
    )
    struct.pack_into("<5I", data, string_ids_off, *string_offsets)
    struct.pack_into("<4I", data, type_ids_off, 0, 1, 2, 3)
    struct.pack_into("<3I", data, proto_ids_off, 2, 2, 0)
    struct.pack_into("<HHI", data, method_ids_off, 0, 0, 4)
    struct.pack_into(
        "<8I", data, class_defs_off, 0, 1, 1, 0, 0xFFFFFFFF, 0, class_data_off, 0
    )
    data[12:32] = hashlib.sha1(data[32:]).digest()
    struct.pack_into("<I", data, 8, zlib.adler32(data[12:]))
    return data


def decoded_instructions(text):
    """Compare operand values, not indentation, hex spelling or range notation."""
    instructions = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("."):
            continue
        opcode, _, operands = line.partition(" ")
        if opcode.startswith("const"):
            register, literal = operands.split(", ")
            line = f"{opcode} {register}, {int(literal.removesuffix('L'), 0)}"
        elif opcode == "filled-new-array/range":
            match = re.fullmatch(r"\{\s*(?:v(\d+) \.\. v(\d+))?\s*\}, (\S+)", operands)
            assert match is not None, line
            start, end, descriptor = match.groups()
            registers = [] if start is None else range(int(start), int(end) + 1)
            values = ", ".join(f"v{register}" for register in registers)
            line = f"{opcode} {{{values}}}, {descriptor}"
        instructions.append(line)
    return instructions


def main():
    binary = str(Path(sys.argv[1]).resolve())
    with tempfile.TemporaryDirectory(prefix="garlic-smali-decode-") as directory:
        fixture = Path(directory, "decode.dex")
        fixture.write_bytes(dex_fixture())
        message = {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "tools/call",
            "params": {
                "name": "smali",
                "arguments": {
                    "path": str(fixture),
                    "class_name": "Decode",
                },
            },
        }
        result = subprocess.run(
            [binary, "-m"],
            input=json.dumps(message) + "\n",
            capture_output=True,
            text=True,
            check=True,
        )
        reply = json.loads(result.stdout)
        text = reply["result"]["content"][0]["text"]
        # Compare every instruction, not just substring matches or output size.
        instructions = decoded_instructions(text)
        assert instructions == EXPECTED, (instructions, EXPECTED, text)
    print(
        "Smali raw DEX regression passed: 9 moves, 30 signed constants, NOP, 3 array ranges and alignment"
    )


if __name__ == "__main__":
    main()
